// 🧭 WHY: `ab-icons/icon-map.ts` holds ALL icons (≈378 KB raw / 31 KB gz). Client components
//    that import it ship every icon. One module per icon lets bundlers keep only what's used:
//    import arrowBack from 'ab-nextjs-icons/ab-icons/icons/arrow_back'

// 📄 fs + paths
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

// 📁 locations
const root = join(dirname(fileURLToPath(import.meta.url)), '..') // 📦 package root
const outDir = join(root, 'ab-icons', 'icons') // 📂 generated modules
const check = process.argv.includes('--check') // 🔎 CI mode

// 🗺️ single source of truth: the generated map (Node ≥ 22.6 strips the TS types)
const { abIconSvg } = await import(pathToFileURL(join(root, 'ab-icons', 'icon-map.ts')).href)

// 🧾 module text for one icon (deterministic → stable diffs)
function moduleFor(name, entry) {
  const lines = [
    '// ⚠️ GENERATED by scripts/icon-modules.mjs — do not edit. Copyright (c) 2026 Abraham Ukachi. The abElements Project. MIT.', // 🏷️
    "import type { AbIconSvgEntry } from '../icon-map' // 🧾 type-only (erased: no map in your bundle)", // 🔗
    '', // ⏎
    `/** 🔣 AbIcon \`${name}\` (outlined${entry.filled ? ' + filled' : ''}, default weight 200). */`, // 📝
    `const ${safeId(name)}: AbIconSvgEntry = {`, // 🧱
    `  outlined: ${JSON.stringify(entry.outlined)},`, // ✏️
    ...(entry.filled ? [`  filled: ${JSON.stringify(entry.filled)},`] : []), // ⬛
    '}', // 🧱
    '', // ⏎
    `export default ${safeId(name)}`, // 📦
    '', // ⏎
  ]
  return lines.join('\n')
}

// 🔤 valid JS identifier from a snake_case name (e.g. 3d_rotation → abIcon_3d_rotation)
function safeId(name) {
  return `abIcon_${name.replace(/[^a-zA-Z0-9_]/g, '_')}` // 🧼
}

// 🧮 expected files
const expected = new Map(Object.entries(abIconSvg).map(([name, entry]) => [`${name}.ts`, moduleFor(name, entry)]))

if (check) {
  // 🔎 compare without writing
  const have = existsSync(outDir) ? readdirSync(outDir).filter((f) => f.endsWith('.ts')) : [] // 📂
  const stale = [...expected].filter(([f, text]) => !existsSync(join(outDir, f)) || readFileSync(join(outDir, f), 'utf8') !== text).map(([f]) => f) // 🧪
  const extra = have.filter((f) => !expected.has(f)) // 🗑️
  if (stale.length || extra.length) {
    console.error(`✖ ab-icons/icons is stale: ${stale.length} missing/changed, ${extra.length} extra. Run: pnpm icons:modules`) // 💥
    process.exit(1)
  }
  console.log(`✔ ab-icons/icons up to date (${expected.size} modules)`) // ✅
} else {
  // ✍️ rewrite from scratch (removes icons that no longer exist)
  rmSync(outDir, { recursive: true, force: true }) // 🧹
  mkdirSync(outDir, { recursive: true }) // 📂
  for (const [f, text] of expected) writeFileSync(join(outDir, f), text) // ✍️
  console.log(`✔ wrote ${expected.size} modules → ab-icons/icons/`) // ✅
}
